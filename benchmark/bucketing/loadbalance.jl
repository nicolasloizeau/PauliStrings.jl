# Load-balance analysis of the bucketing strategies on *representative* string
# collections: operators time-evolved under several models. For each model and
# target size we build O(t), then report, per strategy and bucket count, how
# evenly the multithreaded work would be distributed and how long it takes to
# bucketize the operator.
#
#   julia --project=benchmark benchmark/bucketing/loadbalance.jl
#
# The balance metrics are timing-independent combinatorics; the bucketize column
# is wall-clock, so run single-process. Tunables (env):
#   BUCKET_BITS  bucket-bit counts        (default "6,8,10")
#   BUCKET_M     target #strings, a list  (default "16384,1048576")
#   BUCKET_N     1D qubits                (default 22)
#   BUCKET_STEPS / BUCKET_DT   evolution steps / timestep (default 18 / 0.15)
#
# The balance metrics are reproducible regardless of thread count, while the
# evolution that builds O(t) parallelizes — run with `-t auto` to finish faster
# (~10 min on a many-core workstation).

include(joinpath(@__DIR__, "common.jl"))
using BenchmarkTools
using Printf

const BITS = parse.(Int, split(get(ENV, "BUCKET_BITS", "6,8,10"), ","))
const MS = parse.(Int, split(get(ENV, "BUCKET_M", "16384,1048576"), ","))
const N1D = parse(Int, get(ENV, "BUCKET_N", "22"))
const STEPS = parse(Int, get(ENV, "BUCKET_STEPS", "18"))
const DT = parse(Float64, get(ENV, "BUCKET_DT", "0.15"))
const MD = joinpath(@__DIR__, "..", "bucketing-loadbalance.md")

# qubit count per model (XXZ2D uses a square lattice)
model_N(name) = name == "XXZ2D" ? 25 : N1D

# median bucketize wall-clock (ms) for operator O under strategy s
function bucketize_ms(s, O)
    b = @benchmark ps.bucketize($s, $O) seconds = 0.25
    return minimum(b).time / 1e6
end

io = open(MD, "w")
println(io, "# Bucketing load balance on time-evolved operators\n")
println(io, "How evenly the bucketed `binary_kernel!` distributes work across output")
println(io, "buckets, for operators `O(t)` grown by Heisenberg RK4 evolution under several")
println(io, "models, and how long bucketizing `O(t)` takes. Generated by")
println(io, "`benchmark/bucketing/loadbalance.jl` ($STEPS steps, dt=$DT).\n")
println(io, "Metrics (imbalances: lower = better, `1.00` is perfect):")
println(io, "- **commutator imbalance** = max/mean per-output-bucket work for `[H, O(t)]` (the RK4 kernel call);")
println(io, "- **occupancy imbalance** = max/mean of `O(t)`'s own per-bucket string count;")
println(io, "- **p99** = 99th-percentile bucket work / mean; **empty** = fraction of empty buckets;")
println(io, "- **bucketize** = wall-clock to sort `O(t)` into buckets (one pass; the hash cost differs by family).\n")

model_names = (MODELS_1D..., "XXZ2D")
for name in model_names, M in MS
    N = model_N(name)
    H, O0 = model_HO(name, N)
    O = evolve_to(H, O0; M = M, dt = DT, nsteps = STEPS)
    @info "model $name M=$M: |H|=$(length(H)) |O(t)|=$(length(O))"
    println(io, "## $name — N=$N, target M=$M, |H|=$(length(H)), |O(t)|=$(length(O))\n")
    for b in BITS
        println(io, "### $(1 << b) buckets (b=$b)\n")
        println(io, "| strategy | commutator imbalance | p99 | empty | occupancy imbalance | bucketize (ms) |")
        println(io, "|---|---|---|---|---|---|")
        for (sname, s) in strategies(N, b)
            cw = balance_stats(bucket_work(s, H, O))
            oc = balance_stats(bucket_occupancy(s, O))
            tb = bucketize_ms(s, O)
            @printf(io, "| `%s` | %.2f | %.2f | %.0f%% | %.2f | %.2f |\n",
                sname, cw.imbalance, cw.p99, 100 * cw.empty, oc.imbalance, tb)
        end
        println(io)
        flush(io)
    end
end

println(io, "## Reading this\n")
println(io, "- A strategy parallelizes well when its **commutator imbalance** is close to 1:")
println(io, "  every thread gets a similar share of `[H, O(t)]`.")
println(io, "- `lowbits` keys on the low qubits only and is badly imbalanced for spatially-local")
println(io, "  operators; `Folded`/`Mixing` mix all qubits. `Mixing` (the deterministic full-rank")
println(io, "  matrix `default_strategy` uses) balances best but its per-string hash (B popcounts)")
println(io, "  makes **bucketize** more expensive — the balance/cost trade-off to weigh against the")
println(io, "  kernel's `|A|·|B|` work.")
println(io, "- More buckets (higher `b`) give finer load-balancing granularity, at the cost of more")
println(io, "  empty buckets and a larger `nb²` bucket-pair scan.")
close(io)

@info "Wrote $MD"
