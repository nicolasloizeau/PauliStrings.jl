# Driver: sweep the bucketed kernel's wall-clock across thread counts and
# strategies, on representative time-evolved operands, then render markdown.
# Thread count is fixed at Julia startup, so each count runs as a *separate
# process*.
#
#   julia benchmark/bucketing/run_sweep.jl
#
# Tunables (env): BENCH_THREADS (comma-separated, default "1,2,4,8"), plus the
# BENCH_SECONDS / BENCH_BITS / BENCH_N / BENCH_M tunables consumed by `bench.jl`.
# See `loadbalance.jl` for the (timing-independent) load-balance analysis.

using Printf

const HERE = @__DIR__
const BENCH_PROJECT = dirname(HERE)            # benchmark/
const CSV = joinpath(HERE, "bucketing_results.csv")
const MD = joinpath(BENCH_PROJECT, "bucketing-benchmark.md")

threads = parse.(Int, split(get(ENV, "BENCH_THREADS", "1,2,4,8"), ","))

# Set BENCH_RENDER_ONLY=1 to re-render the markdown from an existing CSV without
# re-timing (useful when only the report layout changed).
const RENDER_ONLY = get(ENV, "BENCH_RENDER_ONLY", "0") == "1"

if !RENDER_ONLY
    open(CSV, "w") do io
        println(io, "nthreads,model,kernel,strategy,N,M,time_s,memory_bytes,allocs,result_len")
    end
    for nt in threads
        @info "Running bench.jl with $nt thread(s)"
        run(`$(Base.julia_cmd()) --project=$BENCH_PROJECT -t $nt $(joinpath(HERE, "bench.jl")) $CSV`)
    end
end

rows = NamedTuple[]
for (i, line) in enumerate(eachline(CSV))
    i == 1 && continue
    f = split(line, ',')
    push!(rows, (
        nt = parse(Int, f[1]), model = f[2], kernel = f[3], strat = f[4],
        N = parse(Int, f[5]), M = parse(Int, f[6]), t = parse(Float64, f[7]),
        mem = parse(Int, f[8]), alloc = parse(Int, f[9]), len = parse(Int, f[10]),
    ))
end

models = unique(r.model for r in rows)
kernels = unique(r.kernel for r in rows)
strats = unique(r.strat for r in rows)
threadset = sort(unique(r.nt for r in rows))
find(model, kernel, strat, nt) = findfirst(r -> r.model == model && r.kernel == kernel && r.strat == strat && r.nt == nt, rows)

open(MD, "w") do io
    println(io, "# Bucketed `binary_kernel!` timing\n")
    println(io, "Wall-clock of the multithreaded bucketed kernel on operators time-evolved")
    println(io, "under several models, vs the serial baseline. Generated by")
    println(io, "`benchmark/bucketing/run_sweep.jl`. See `bucketing-loadbalance.md` for the")
    println(io, "per-strategy load-balance analysis.\n")
    println(io, "- Thread counts: $(join(threadset, ", "))")
    println(io, "- Strategies: $(join(strats, ", "))")
    println(io, "- `commutator_HO` = `[H, O(t)]` (the RK4 kernel call); `sqr_OO` = `O(t)·O(t)`.\n")

    for kernel in kernels, model in models
        r0i = findfirst(r -> r.model == model, rows)
        r0i === nothing && continue
        r0 = rows[r0i]
        println(io, "## $kernel — $model (N=$(r0.N), M=$(r0.M))\n")
        sb = find(model, kernel, "Serial", minimum(threadset))
        tser = sb === nothing ? NaN : rows[sb].t

        # Two speedups are reported separately:
        #   * vs main @t=1   = serial(t=1) / strategy(t=1) — the pure bucketing win on one
        #     thread (main's kernel is the `Serial` row), independent of threading;
        #   * thread scaling = strategy(t=1) / strategy(t=max) — the multithreading speedup
        #     of that strategy over its own single-thread time.
        ntmax = maximum(threadset)
        print(io, "| strategy |")
        for nt in threadset; print(io, " t=$nt (ms) |"); end
        println(io, " vs main @t=1 | thread scaling (t=1→$ntmax) | best vs main |")
        print(io, "|---|")
        for _ in threadset; print(io, "---|"); end
        println(io, "---|---|---|")
        for strat in strats
            print(io, "| `$strat` |")
            best = Inf
            for nt in threadset
                k = find(model, kernel, strat, nt)
                if k === nothing
                    print(io, " — |")
                else
                    best = min(best, rows[k].t)
                    print(io, " $(@sprintf("%.2f", rows[k].t * 1e3)) |")
                end
            end
            k1 = find(model, kernel, strat, minimum(threadset))
            kmax = find(model, kernel, strat, ntmax)
            t1 = k1 === nothing ? NaN : rows[k1].t
            tmax = kmax === nothing ? NaN : rows[kmax].t
            vsmain1 = isfinite(tser) && isfinite(t1) && t1 > 0 ? tser / t1 : NaN
            scaling = isfinite(t1) && isfinite(tmax) && tmax > 0 ? t1 / tmax : NaN
            bestvs = isfinite(tser) && isfinite(best) && best > 0 ? tser / best : NaN
            println(io, " $(@sprintf("%.2fx", vsmain1)) | $(@sprintf("%.2fx", scaling)) | $(@sprintf("%.2fx", bestvs)) |")
        end
        println(io)
    end

    println(io, "## Notes\n")
    println(io, "- `Serial` is the reference single-threaded kernel — identical to the `main` branch.")
    println(io, "- **vs main @t=1** isolates the bucketing win on a single thread (smaller, cache-")
    println(io, "  resident per-bucket dictionaries instead of one large one); **thread scaling** is")
    println(io, "  the multithreading speedup of a strategy over its own single-thread time; **best")
    println(io, "  vs main** is the combined wall-clock speedup over `main`.")
    println(io, "- Operands have one small operand (`H`) for `commutator_HO`; `sqr_OO` is the")
    println(io, "  heavier `O·O` workload that benefits most from threads.")
end

@info "Wrote $MD"
println(read(MD, String))
